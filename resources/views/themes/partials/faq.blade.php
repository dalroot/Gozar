<!-- Strict Category Filtering JS (Only 4 items on 'general' tab, search queries search ALL categories) -->
<script>
document.addEventListener('DOMContentLoaded', function() {
    const searchInput = document.getElementById('faq-search-input');
    const clearBtn = document.getElementById('faq-clear-search');
    const tabs = document.querySelectorAll('.faq-tab');
    const faqItems = document.querySelectorAll('.faq-item');
    const emptyState = document.querySelector('.faq-empty');

    let activeCategory = 'general'; // Default: Only show general 4 questions

    function filterFAQ() {
        const query = searchInput ? searchInput.value.trim().toLowerCase() : '';
        let visibleCount = 0;

        if (query.length > 0 && clearBtn) {
            clearBtn.classList.remove('hidden');
        } else if (clearBtn) {
            clearBtn.classList.add('hidden');
        }

        faqItems.forEach(item => {
            const itemCategory = item.getAttribute('data-category');
            const keywords = (item.getAttribute('data-keywords') || '').toLowerCase();
            const textContent = item.textContent.toLowerCase();

            // If user is searching, search ACROSS ALL CATEGORIES!
            // If user is NOT searching, match STRICT activeCategory ONLY!
            let shouldShow = false;

            if (query.length > 0) {
                const matchesQuery = keywords.includes(query) || textContent.includes(query);
                shouldShow = matchesQuery;
            } else {
                shouldShow = (itemCategory === activeCategory);
            }

            if (shouldShow) {
                item.style.display = 'block';
                visibleCount++;
            } else {
                item.style.display = 'none';
            }
        });

        if (emptyState) {
            emptyState.style.display = (visibleCount === 0) ? 'block' : 'none';
        }
    }

    // Tab Click Event
    tabs.forEach(tab => {
        tab.addEventListener('click', function() {
            tabs.forEach(t => t.classList.remove('active'));
            this.classList.add('active');
            activeCategory = this.getAttribute('data-category');
            
            // Clear search when switching tabs for a clean experience
            if (searchInput) searchInput.value = '';
            filterFAQ();
        });
    });

    // Search Input Event
    if (searchInput) {
        searchInput.addEventListener('input', filterFAQ);
    }

    // Clear Search Event
    if (clearBtn) {
        clearBtn.addEventListener('click', function() {
            if (searchInput) searchInput.value = '';
            filterFAQ();
        });
    }

    // Accordion Toggle Logic
    const questions = document.querySelectorAll('.faq-question');
    questions.forEach(q => {
        q.addEventListener('click', function() {
            const parent = this.closest('.faq-item');
            const isOpen = parent.classList.contains('open');

            // Close siblings
            faqItems.forEach(item => item.classList.remove('open'));

            if (!isOpen) {
                parent.classList.add('open');
                this.setAttribute('aria-expanded', 'true');
            } else {
                this.setAttribute('aria-expanded', 'false');
            }
        });
    });

    // Run initial filter on page load so ONLY general items are shown!
    filterFAQ();
});
</script>
