            // Update button attributes and action handlers
            const updateButtonActions = () => {
                const activePeriod = document.querySelector('.pricing-period-btn.active')?.getAttribute('data-period') || 'quarterly';
                
                ['core', 'pro', 'enterprise'].forEach(type => {
                    const btn = document.getElementById('btn-' + type);
                    if (btn) {
                        const planId = customPricing[activePeriod][type].id;
                        if (planId) {
                            btn.setAttribute('data-plan-id', planId);
                        }
                    }
                });
            };
            
            updateButtonActions();
            
            // Hook price switcher buttons to update data-plan-ids as well
            document.querySelectorAll('.pricing-period-btn').forEach(btn => {
                btn.addEventListener('click', () => {
                    setTimeout(updateButtonActions, 50);
                });
            });
            
            // Handle checkout form submission to Laravel's order store!
            const buyButtons = document.querySelectorAll('.buy-btn');
            const checkoutForm = document.getElementById('checkout-web-form');
            
            buyButtons.forEach(btn => {
