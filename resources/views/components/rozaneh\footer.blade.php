            plans.forEach(plan => {
                let type = 'core';
                const nameLower = plan.name.toLowerCase();
                if (nameLower.includes('افق') || nameLower.includes('pro') || plan.is_popular) {
                    type = 'pro';
                } else if (nameLower.includes('بینهایت') || nameLower.includes('enterprise') || nameLower.includes('بینایت')) {
                    type = 'enterprise';
                }
                
                let period = 'monthly';
                let periodText = 'تومان / ماهانه';
                if (plan.duration_days >= 365) {
                    period = 'yearly';
                    periodText = 'تومان / سالانه';
                } else if (plan.duration_days >= 90) {
                    period = 'quarterly';
                    periodText = 'تومان / ۳ ماهه';
                }
                
                customPricing[period][type] = {
                    price: formatPrice(plan.price),
                    period: periodText,
                    rawPrice: formatPrice(plan.price) + ' ' + periodText,
                    id: plan.id
                };
            });

            // Set global variable so script.js uses it
            window.pricingData = customPricing;
            
            // Trigger UI update with selected period values
